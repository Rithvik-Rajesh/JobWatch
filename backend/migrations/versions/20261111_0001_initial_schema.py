# Full-text search vector for jobs. Weighted: title & company (A), skills (B), department (C),
# description (D). Maintained by trigger so every write path (ingest, manual, merge) stays consistent.
SEARCH_TRIGGER = """
create or replace function jobs_search_vector_update() returns trigger language plpgsql as $$
declare company_name text;
begin
  select name into company_name from companies where id = new.company_id;
  new.search_vector :=
      setweight(to_tsvector('simple', unaccent(coalesce(new.title, ''))), 'A')
   || setweight(to_tsvector('simple', unaccent(coalesce(company_name, ''))), 'A')
   || setweight(to_tsvector('simple', unaccent(array_to_string(new.skills, ' '))), 'B')
   || setweight(to_tsvector('simple', unaccent(coalesce(new.department, ''))), 'C')
   || setweight(to_tsvector('english', unaccent(left(coalesce(new.description_text, ''), 200000))), 'D');
  return new;
end $$;

create trigger jobs_search_vector_trg
  before insert or update of title, skills, department, description_text, company_id on jobs
  for each row execute function jobs_search_vector_update();

-- Keep job search vectors in sync when a company is renamed.
create or replace function companies_name_propagate() returns trigger language plpgsql as $$
begin
  if new.name is distinct from old.name then
    update jobs set company_id = company_id where company_id = new.id;
  end if;
  return new;
end $$;

create trigger companies_name_propagate_trg
  after update of name on companies
  for each row execute function companies_name_propagate();
"""

